/*
=========================================
        ACCESS MODIFIERS IN JAVA
=========================================

Definition:
Access Modifiers are keywords in Java that control
who can access classes, variables, methods, and constructors.

There are 4 access modifiers:

1. public
   - Can be accessed from anywhere.
   - Least restrictive access modifier.

2. private
   - Can be accessed only inside the same class.
   - Most restrictive access modifier.

3. protected
   - Can be accessed within the same package.
   - Can also be accessed by child (subclass) classes.

4. default (No keyword)
   - If no access modifier is written, Java uses default access.
   - Can be accessed only within the same package.

Easy Trick:
public    -> Everyone
protected -> Same Package + Child Class
default   -> Same Package Only
private   -> Same Class Only
*/
