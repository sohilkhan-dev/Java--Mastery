package loops;

public class forloops {
    public static void main(String[] args) {
        for(int i=1;i<=4;i++){
            System.out.println("hii " + i);
            for(int j=1;j<=3;j++){
                System.out.println("hello " + j);
            }
        }
        System.out.println("bye  " + 5);
    }

    
}
